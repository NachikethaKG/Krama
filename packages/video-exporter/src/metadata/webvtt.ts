import type { TutorialSpec, WordTiming } from "@krama/contracts-ts";

/**
 * Formats a millisecond duration into WebVTT timestamp format (HH:MM:SS.mmm).
 */
export function formatVttTimestamp(ms: number): string {
  const totalSeconds = Math.floor(ms / 1000);
  const milliseconds = Math.floor(ms % 1000);

  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  const pad2 = (n: number) => String(n).padStart(2, "0");
  const pad3 = (n: number) => String(n).padStart(3, "0");

  return `${pad2(hours)}:${pad2(minutes)}:${pad2(seconds)}.${pad3(milliseconds)}`;
}

/**
 * Generates standard WebVTT sidecar captions from TutorialSpec and timeline offsets (Decision D11).
 */
export function generateWebVTT(spec: TutorialSpec, introDurationMs = 2000): string {
  const blocks: string[] = ["WEBVTT - Generated by Krama", ""];

  let sceneStartMs = introDurationMs;
  let cueIndex = 1;

  for (const scene of spec.scenes) {
    const text = scene.caption?.text?.trim();
    if (!text) {
      sceneStartMs += scene.duration_ms;
      continue;
    }

    // Lead-in offset (default 300ms from decision D4)
    const audioLeadInMs = 300;
    const captionStart = sceneStartMs + audioLeadInMs;
    const captionEnd = Math.max(captionStart + 500, sceneStartMs + scene.duration_ms - 200);

    blocks.push(String(cueIndex));
    blocks.push(`${formatVttTimestamp(captionStart)} --> ${formatVttTimestamp(captionEnd)}`);
    blocks.push(text);
    blocks.push("");

    cueIndex++;
    sceneStartMs += scene.duration_ms;
  }

  return blocks.join("\n");
}
