import { describe, expect, it } from "vitest";
import type { TutorialSpec } from "@krama/contracts-ts";
import { formatVttTimestamp, generateWebVTT } from "../src/metadata/webvtt.js";

describe("WebVTT Sidecar Subtitles (Decision D11)", () => {
  it("formats timestamps into HH:MM:SS.mmm correctly", () => {
    expect(formatVttTimestamp(0)).toBe("00:00:00.000");
    expect(formatVttTimestamp(1500)).toBe("00:00:01.500");
    expect(formatVttTimestamp(65432)).toBe("00:01:05.432");
    expect(formatVttTimestamp(3661005)).toBe("01:01:01.005");
  });

  it("generates standard WebVTT subtitles with sequence numbers and timing cues", () => {
    const spec: TutorialSpec = {
      version: "1.0",
      workflow_id: "wf-vtt",
      title: "Sample Spec",
      viewport: { width: 1280, height: 800 },
      total_duration_ms: 7000,
      scenes: [
        {
          id: "s1",
          step_seq: 1,
          start_ms: 0,
          duration_ms: 4000,
          action: { type: "click" },
          recording: { start_ms: 0, end_ms: 4000 },
          caption: { text: "Click on New Repository." },
        },
        {
          id: "s2",
          step_seq: 2,
          start_ms: 4000,
          duration_ms: 3000,
          action: { type: "fill", value: "repo" },
          recording: { start_ms: 4000, end_ms: 7000 },
          caption: { text: "Type the repository name." },
        },
      ],
    };

    const vtt = generateWebVTT(spec, 2000); // 2000ms intro

    expect(vtt).toContain("WEBVTT - Generated by Krama");
    expect(vtt).toContain("1\n00:00:02.300 --> 00:00:05.800\nClick on New Repository.");
    expect(vtt).toContain("2\n00:00:06.300 --> 00:00:08.800\nType the repository name.");
  });
});
