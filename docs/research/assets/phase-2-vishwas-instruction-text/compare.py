"""Side-by-side table of every provider's text per step (comparison.md), plus the 'before' texts.

'Before' = what the planner writes today: the stored Phase 1 workflow and the live hinted plans for the 4 new tasks.
Run from this folder:  python compare.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
PROVIDERS = ["template", "gemini-gemini-3.8-flash", "gemini-gemini-3.5-flash", "gemini-gemini-2.5-flash", "ollama-llama3.1-8b"]


def cell(t: str) -> str:
    return t.replace("|", "\\|").replace("\n", "\\n") or "—"


def main() -> None:
    outs = {p: json.loads((HERE / f"out-{p}.json").read_text(encoding="utf-8")) for p in PROVIDERS
            if (HERE / f"out-{p}.json").exists()}
    lines = ["# Instruction text, side by side", "",
             "Generated by `compare.py` from `out-*.json`. `—` = no output (quota error).", ""]
    lines += ["## Before: what the planner writes today", "",
              "Stored Phase 1 workflow `c4a44aac` (create repo): \"Click the New Repository link.\" · "
              "\"Enter my-test-1 into the repository name input.\" · \"Click the Create Repository button.\"", ""]
    hinted = json.loads((HERE.parent / "phase-2-vishwas-gitea-tasks" / "plans-live-hints-1.json").read_text(encoding="utf-8"))
    for task, plan in hinted.items():
        lines.append(f"- **{task}** (gemini-2.5-flash plan): " + " · ".join(f"\"{s['instruction_text']}\"" for s in plan["steps"]))
    lines += ["", "## After: rewrite from the executed steps", ""]
    names = list(outs)
    lines += ["| task | step | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    first = outs[names[0]]
    for task, t in first["tasks"].items():
        for i, s in enumerate(t["steps"]):
            label = s["in"].get("label") or s["in"].get("value") or ""
            row = [cell(outs[n]["tasks"][task]["steps"][i]["text"]) for n in names]
            lines.append(f"| {task} | {s['in']['seq']} {s['in']['action']} {cell(label)[:28]} | " + " | ".join(row) + " |")
    lines += ["", "## Automatic checks (steps passing all / 22) and time", "",
              "| provider | all checks | seconds (5 workflows) | errors |", "|---|---|---|---|"]
    for n, o in outs.items():
        sm = o["summary"]
        lines.append(f"| {n} | {sm['all_pass']}/{sm['steps']} | {sm['seconds_total']} | {sm['errors']} |")
    (HERE / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
